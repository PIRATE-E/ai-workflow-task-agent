"""
TicketOut Data Model (Headless Core Output Contract)

=============================================================================
WHAT CHANGED & WHY:
- Converted fields from UPPERCASE (STATUS, TRANSCRIPT) to snake_case (status, transcript):
  1. Conforms to standard Pydantic v2 and Python naming conventions.
  2. Ensures direct deserialization into Rust Serde structs in ai-workflow-gui.
- Added `ticket_id: str | int`:
  Enables the host platform to correlate this output with the initiating TicketIn,
  which is critical in asynchronous, event-driven, or concurrent execution.
- Retained status as Literal["COMPLETED", "FAILED", "TIMED_OUT"]:
  Directly matches the state machine transitions defined in
  reports/new_wind_ai/COLD_WIND_ARCHITECTURE_BASE.md §7.
- Retained new_working_state as `dict[str, Any]`:
  The updated conversation state returned to the platform for storage
  (e.g., in a database or file). Core maintains zero disk persistence.
- Retained error_info as optional (`dict[str, Any] | None`):
  Captures structured error metadata when status != "COMPLETED".
=============================================================================
"""

from typing import Any, Literal
from pydantic import BaseModel, Field


class TicketOut(BaseModel):
    """
    Structured execution result produced by ColdWind Core upon completing a TicketIn turn.
    """

    ticket_id: str | int = Field(
        ...,
        description="Matches ticket_id of the initiating TicketIn for request-response correlation",
    )
    status: Literal["COMPLETED", "FAILED", "TIMED_OUT"] = Field(
        ...,
        description="Outcome status of the turn execution per architecture state machine",
    )
    new_working_state: dict[str, Any] = Field(
        ...,
        description="Updated conversational state to be persisted by the platform",
    )
    transcript: str = Field(
        ...,
        description="Final assistant text reply generated by Core for display",
    )
    usage: dict[str, Any] = Field(
        ...,
        description="Resource metrics consumed during turn execution (tokens, tool count, latency)",
    )
    error_info: dict[str, Any] | None = Field(
        default=None,
        description="Structured error details if status is FAILED or TIMED_OUT",
    )
